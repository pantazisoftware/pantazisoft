/**
 * Builds every text-free piece of the PantaziSoft media kit from the mark in
 * brand-mark.mjs:
 *
 *   node scripts/brand-kit.mjs
 *
 * Writes
 *   public/logo-transparent.svg / .png   the mark, ink and lime, tight box
 *   public/logo-icon.svg                 app-icon source (run `npm run icons` after)
 *   public/logo-green-bg.svg             the mark on lime
 *   public/logo.png                      the app icon, large
 *   public/brand/styles/                 the mark in every style, light and dark
 *   public/brand/patterns/               seamless wave tiles, SVG and PNG
 *   public/brand/backgrounds/            backgrounds and wallpapers
 *
 * Anything with type in it (lockup PNGs, social covers, the OG card) needs the
 * brand fonts and goes through the browser artboards and finish-brand.mjs.
 */

import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import sharp from "sharp";
import {
  INK, LIME, PAPER, W, H, solid, styles, STYLE_VIEWBOX, pattern,
} from "./brand-mark.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pub = join(root, "public");
const brand = join(pub, "brand");

const log = (file, note) => console.log(file.padEnd(46), note);
const svgDoc = (viewBox, body, attrs = "") =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${attrs}>${body}</svg>\n`;
const png = (svg, width, height) =>
  sharp(Buffer.from(svg), { density: 600 }).resize(width, height, { fit: "fill" }).png({ compressionLevel: 9 });

async function out(path, data) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, data);
}

/* ── The mark on the site, and the icon sources ────────────────────────── */

const MARK_NOTE = `
  PantaziSoft mark — the wave. Generated by scripts/brand-kit.mjs from
  scripts/brand-mark.mjs; edit those, not this file.

  Two half-discs of radius 35 on one line: ink rising from x 0–70, lime
  falling from x 30–100. The box is the mark's tight bounds, 100 × 70.`;

await out(join(pub, "logo-transparent.svg"),
  svgDoc(`0 0 ${W} ${H}`, `<!--${MARK_NOTE}\n-->${solid(INK, LIME)}`, ` role="img" aria-label="PantaziSoft"`));
log("logo-transparent.svg", "vector");

/** The mark centred in a square, at `scale` (350 of 512 units wide). */
const iconSvg = (bg, main, accent, note) => {
  const scale = 3.5, w = W * scale, h = H * scale;
  const x = (512 - w) / 2, y = (512 - h) / 2;
  return svgDoc("0 0 512 512",
    `<!--\n  ${note}\n\n  The wave at 3.5× (350 × 245 units), centred on the canvas. The mark is\n  point-symmetric — its weight sits top-left and bottom-right in equal\n  measure — so the box centre is also the optical centre.\n-->` +
    `<path fill="${bg}" d="M0 0h512v512H0z"/><g transform="translate(${x} ${y}) scale(${scale})">${solid(main, accent)}</g>`,
    ` width="512" height="512" role="img" aria-label="PantaziSoft"`);
};

const icon = iconSvg(INK, PAPER, LIME,
  "PantaziSoft app icon: the source every favicon and touch icon is rasterised\n  from. Generated by scripts/brand-kit.mjs; run `npm run icons` afterwards.");
await out(join(pub, "logo-icon.svg"), icon);
log("logo-icon.svg", "vector");

await out(join(pub, "logo-green-bg.svg"), iconSvg(LIME, INK, PAPER,
  "The mark on brand lime. The falling half turns white here: lime on lime\n  would vanish."));
log("logo-green-bg.svg", "vector");

await png(icon, 1656, 1656).toFile(join(pub, "logo.png"));
log("logo.png", "1656x1656");
await png(svgDoc(`0 0 ${W} ${H}`, solid(INK, LIME)), 1600, 1120).toFile(join(pub, "logo-transparent.png"));
log("logo-transparent.png", "1600x1120");

/* ── Styles ────────────────────────────────────────────────────────────── */

for (const [name, draw] of Object.entries(styles)) {
  for (const [tone, main] of [["light", INK], ["dark", PAPER]]) {
    const svg = svgDoc(STYLE_VIEWBOX, draw(main));
    const base = join(brand, "styles", `wave-${name}-${tone}`);
    await out(`${base}.svg`, svg);
    await png(svg, 1080, 780).toFile(`${base}.png`);
    log(`brand/styles/wave-${name}-${tone}`, "svg + png 1080x780");
  }
}

/* ── Patterns ──────────────────────────────────────────────────────────────
   8 × 8 cells: even on both axes, so the tile repeats without a seam. */

const TILES = {
  light: { bg: "#f4f4f0", main: INK, accent: LIME },
  dark: { bg: INK, main: "#26262a", accent: "#4f7f12" },
  lime: { bg: LIME, main: INK, accent: PAPER },
};
for (const [name, t] of Object.entries(TILES)) {
  const body = `<rect width="400" height="400" fill="${t.bg}"/>` +
    pattern({ cols: 8, rows: 8, size: 50, main: t.main, accent: t.accent, accentRate: 0.12, seed: 11 });
  const svg = svgDoc("0 0 400 400", body, ` width="400" height="400"`);
  await out(join(brand, "patterns", `wave-pattern-${name}.svg`), svg);
  await png(svg, 2048, 2048).toFile(join(brand, "patterns", `wave-pattern-${name}.png`));
  log(`brand/patterns/wave-pattern-${name}`, "svg tile + png 2048");
}

/* ── Backgrounds ───────────────────────────────────────────────────────────
   The pattern fades in from the edges and leaves the middle calm, where a
   face on a call or icons on a desktop will sit; the mark sits small in one
   corner. */

function background(w, h, { bg, main, accent, mark, cell, markW }) {
  const cols = Math.ceil(w / cell) + 1, rows = Math.ceil(h / cell) + 1;
  const mh = markW * (H / W), pad = Math.round(Math.min(w, h) * 0.06);
  return svgDoc(`0 0 ${w} ${h}`,
    `<defs>
      <radialGradient id="fade" cx="0.42" cy="0.45" r="0.75">
        <stop offset="0.18" stop-color="#000"/><stop offset="0.85" stop-color="#fff"/>
      </radialGradient>
      <mask id="m"><rect width="${w}" height="${h}" fill="url(#fade)"/></mask>
    </defs>
    <rect width="${w}" height="${h}" fill="${bg}"/>
    <g mask="url(#m)">${pattern({ cols, rows, size: cell, main, accent, accentRate: 0.1, seed: 5 })}</g>
    <g transform="translate(${w - pad - markW} ${h - pad - mh}) scale(${markW / W})">${solid(mark[0], mark[1])}</g>`,
    ` width="${w}" height="${h}"`);
}

const DARK = { bg: INK, main: "#2c2c31", accent: "#5c9416", mark: [PAPER, LIME] };
const LIGHT = { bg: "#f4f4f0", main: "#dcdcd3", accent: "#b9e07c", mark: [INK, LIME] };
const BACKGROUNDS = [
  ["background-dark-1920x1080", 1920, 1080, DARK, 96, 150],
  ["background-light-1920x1080", 1920, 1080, LIGHT, 96, 150],
  ["wallpaper-dark-2560x1440", 2560, 1440, DARK, 128, 200],
  ["wallpaper-light-2560x1440", 2560, 1440, LIGHT, 128, 200],
  ["wallpaper-phone-dark-1179x2556", 1179, 2556, DARK, 98, 170],
];
await mkdir(join(brand, "backgrounds"), { recursive: true });
for (const [name, w, h, look, cell, markW] of BACKGROUNDS) {
  await png(background(w, h, { ...look, cell, markW }), w, h)
    .toFile(join(brand, "backgrounds", `${name}.png`));
  log(`brand/backgrounds/${name}.png`, `${w}x${h}`);
}
